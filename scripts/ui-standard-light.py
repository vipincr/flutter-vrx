#!/usr/bin/env python3
"""The compositor's numbers from the vrx UI standard (vrx plan 0033 D2, D6).

    scripts/ui-standard-light.py STANDARD.toml            write src/vrx_light_standard.h
    scripts/ui-standard-light.py STANDARD.toml --check    exit 1 when the header is not what STANDARD.toml gives

STANDARD.toml is the resolved standard vrx-linux vendors (flutter/vrx_kit/standard/vrx-ui-standard.toml);
the header records its sha256, so the vendored file's pin and this header are bumped together.
The compositor never spells a floor or a duration: it includes the header.
"""
import hashlib
import pathlib
import sys
import tomllib

HEADER = pathlib.Path(__file__).resolve().parent.parent / "src" / "vrx_light_standard.h"


def render(path: pathlib.Path) -> str:
    raw = path.read_bytes()
    doc = tomllib.loads(raw.decode())
    light = doc["light"]
    through = doc["transition"]["through_dark"]
    return (
        "// GENERATED by scripts/ui-standard-light.py from the vrx UI standard (vrx-linux's vendored\n"
        "// flutter/vrx_kit/standard/vrx-ui-standard.toml). Do not edit: re-vendor the standard, run the script.\n"
        f"// standard sha256 {hashlib.sha256(raw).hexdigest()}\n"
        "#ifndef VRX_LIGHT_STANDARD_H\n"
        "#define VRX_LIGHT_STANDARD_H\n"
        "\n"
        "// [light] lit_floor_permille: the dimmest a lit screen goes\n"
        f"#define VRX_STD_LIGHT_FLOOR_PERMILLE {int(light['lit_floor_permille'])}u\n"
        "// [transition.through_dark]\n"
        f"#define VRX_STD_THROUGH_DARK_OUT_MS {int(through['out_ms'])}u\n"
        f"#define VRX_STD_THROUGH_DARK_IN_MS {int(through['in_ms'])}u\n"
        "\n"
        "#endif\n"
    )


def main() -> int:
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    if len(args) != 1:
        print(__doc__)
        return 2
    want = render(pathlib.Path(args[0]))
    if "--check" in sys.argv:
        if not HEADER.exists() or HEADER.read_text() != want:
            print(f"{HEADER} is not what {args[0]} gives: run scripts/ui-standard-light.py")
            return 1
        return 0
    HEADER.write_text(want)
    return 0


if __name__ == "__main__":
    sys.exit(main())
